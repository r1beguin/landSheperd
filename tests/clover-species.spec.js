/**
 * Helper function to force a plant to a specific growth stage
 * @param {Page} page - Playwright page object
 * @param {number} gridX - Grid X coordinate
 * @param {number} gridY - Grid Y coordinate
 * @param {string} layer - Layer ('bottom', 'middle', 'top')
 * @param {string} targetStage - Target stage name
 * @returns {Promise<boolean>} Success status
 */
async function forceGrowthStage(page, gridX, gridY, layer, targetStage) {
    return await page.evaluate(([x, y, l, stage]) => {
        const pm = window.graphicsEngine.plantManager;
        const plant = pm.getPlantAt(x, y, l);
        if (plant) {
            const speciesId = plant.species?.id;
            if (!speciesId) {
                console.error('Plant has no species ID');
                return false;
            }
            
            const config = pm.speciesConfigs.get(speciesId);
            if (!config) {
                console.error(`No config found for species: ${speciesId}`);
                return false;
            }
            
            plant.stage = stage;
            plant.currentStage = stage;
            plant.sprite = window.PlantGenerator.generatePlantSprite(config, stage);
            return true;
        }
        return false;
    }, [gridX, gridY, layer, targetStage]);
}

/**
 * Helper function to spawn a plant at specific grid coordinates
 * @param {Page} page - Playwright page object
 * @param {number} gridX - Grid X coordinate
 * @param {number} gridY - Grid Y coordinate
 * @param {string} speciesId - Species ID (default: 'trifolium_repens')
 * @param {string} stage - Optional growth stage (will not force regenerate sprite)
 * @returns {Promise<Object>} Plant info or null
 */
async function spawnPlantAt(page, gridX, gridY, speciesId = 'trifolium_repens', stage = null) {
    return await page.evaluate(([x, y, species, targetStage]) => {
        if (!window.graphicsEngine || !window.graphicsEngine.plantManager) {
            return null;
        }
        
        const plant = window.graphicsEngine.plantManager.addPlant(x, y, species);
        
        if (!plant) {
            return null;
        }
        
        // If target stage specified, just set it (don't regenerate sprite to avoid errors)
        // The plant already has a sprite from addPlant
        if (targetStage) {
            plant.stage = targetStage;
            plant.currentStage = targetStage;
            // Keep existing sprite - it's already generated by addPlant
        }
        
        return {
            success: true,
            species: plant.species?.id || species,
            layer: plant.getLayer ? plant.getLayer() : plant.layer,
            stage: plant.stage,
            grid: { x, y }
        };
    }, [gridX, gridY, speciesId, stage]);
}

/**
 * Helper to get screen position for grid coordinates
 */
async function getScreenPosition(page, gridX, gridY) {
    return await page.evaluate(([x, y]) => {
        const cam = window.graphicsEngine.cameraManager;
        const sm = window.graphicsEngine.soilManager;
        const worldX = x * sm.cellSize + sm.cellSize / 2;
        const worldY = y * sm.cellSize + sm.cellSize / 2;
        return cam.worldToScreen(worldX, worldY);
    }, [gridX, gridY]);
}

